"""EP04 練習題答案與 sims/offshore.html 預設情境：組裝外移的工資算術、照抄落後、飛彈命中率。
用法：python3 calc_u04.py

  每顆組裝成本（本土）  c_US = w_US * t / 60
  每顆組裝成本（海外）  c_A  = w_A * t / (60 * s) + f + o + tau * (海外加值)
     w：時薪（美元）、t：每顆組裝分鐘、s：相對工作速度、f：來回運費、o：海外管理品管、tau：關稅率
  照抄落後比例          N_蘇 / N_美 = 2^(-L / T2)
  至少一發命中          P = 1 - (1 - p)^n
書中數字（Miller 2022，1960 年代中期）：香港約 25 美分／小時、約為美國十分之一；臺灣 19、馬來西亞 15、新加坡 11、南韓 10 美分。
美國對照：BLS 1965 年製造業生產工人平均時薪 2.61 美元。工時、速度、運費、管理成本、關稅率均為教學假設。"""

US = 2.61
ASIA = {"香港": 0.25, "臺灣": 0.19, "馬來西亞": 0.15, "新加坡": 0.11, "南韓": 0.10}

# ---------- Q1 工資倍數
print(f"Q1 美國 ÷ 香港 = {US/0.25:.2f} 倍（書中說香港約為美國十分之一）")

# ---------- Q2 每顆組裝 3 分鐘，只算人工
t = 3
cus, chk = US * t / 60, 0.25 * t / 60
print(f"Q2 美國 {cus*100:.2f} 美分、香港 {chk*100:.2f} 美分，每顆省 {(cus-chk)*100:.1f} 美分")

# ---------- sim 預設情境（與 offshore.html 相同）
def cost_asia(w, t=3, s=1.0, f=0.01, o=0.01, tau=0.06, die=0.50, rule807=True):
    labor = w * t / 60 / s
    base = labor + o if rule807 else labor + o + die
    return labor + f + o + tau * base

for k, w in ASIA.items():
    print(f"[預設] {k}：每顆 {cost_asia(w)*100:.2f} 美分（美國 {US*3/60*100:.2f} 美分）")

# 損益兩平工時：US*t/60 = w*t/(60 s)*(1+tau) + f + o*(1+tau)
def breakeven_t(w, s=1.0, f=0.01, o=0.01, tau=0.06):
    return 60 * (f + o * (1 + tau)) / (US - w / s * (1 + tau))
print(f"[預設] 香港損益兩平：每顆組裝至少 {breakeven_t(0.25)*60:.1f} 秒")
saving = (US * 3 / 60 - cost_asia(0.25))
print(f"[預設] 以書中香港廠第一年 1.2 億個元件估：省 {saving*1.2e8/1e6:.1f} 百萬美元（示意）")

# ---------- Q3 照抄落後：落後 4 年、T2 = 2 年
L, T2 = 4, 2
print(f"Q3 落後 {L} 年 → 電晶體數只有美國的 {2**(-L/T2):.0%}")

