"""EP10 練習題答案與網頁數字：中國晶片進口 vs 原油進口、Arm 中國、大基金。
用法：python3 calc_u10.py

資料來源（sims/imports.html 用同一份數字）：
  UN Comtrade，申報國＝中國（reporterCode 156），夥伴＝全世界，年度，進口 CIF 美元。
  HS 8542＝電子積體電路（晶片），HS 2709＝原油。查詢日 2026-11-18。
  https://comtradeapi.un.org/public/v1/preview/C/A/HS?reporterCode=156&period=2025&partnerCode=0&cmdCode=8542,2709&flowCode=M
其他：
  軟銀收購 Arm：軟銀 2016-07-18 新聞稿，約 240 億英鎊（約 310 億美元）https://group.softbank/en/news/press/20160718
  Arm 中國 51% 股權 7.75 億美元、占 Arm 營收五分之一（書中，軟銀說法，2018）
  大基金：一期 1,387 億、二期 2,040 億、三期 3,440 億人民幣（第一財經 2024-05-24）
"""

# 單位：十億美元（billion USD），UN Comtrade 原值四捨五入到 0.001
IC = {2000: 13.800, 2001: 16.998, 2002: 26.374, 2003: 41.834, 2004: 61.707, 2005: 82.202,
      2006: 107.152, 2007: 128.664, 2008: 130.583, 2009: 120.751, 2010: 158.010, 2011: 171.142,
      2012: 192.967, 2013: 232.078, 2014: 218.520, 2015: 230.657, 2016: 227.617, 2017: 261.161,
      2018: 312.952, 2019: 306.397, 2020: 350.770, 2021: 432.634, 2022: 416.525, 2023: 350.139,
      2024: 386.119, 2025: 425.394}
OIL = {2000: 14.861, 2001: 11.661, 2002: 12.757, 2003: 19.782, 2004: 33.912, 2005: 47.723,
       2006: 66.412, 2007: 79.858, 2008: 129.331, 2009: 89.256, 2010: 135.300, 2011: 196.771,
       2012: 220.794, 2013: 219.660, 2014: 228.288, 2015: 134.343, 2016: 116.661, 2017: 163.821,
       2018: 240.380, 2019: 242.385, 2020: 178.453, 2021: 258.523, 2022: 365.512, 2023: 337.645,
       2024: 325.187, 2025: 295.447}

# ---------- 網頁：哪些年晶片進口高於原油
over = [y for y in IC if IC[y] > OIL[y]]
under = [y for y in IC if IC[y] <= OIL[y]]
print(f"[網頁] 2000–2025 共 {len(IC)} 年，晶片進口＞原油進口 {len(over)} 年；原油較高的年份：{under}")
y00s = [y for y in range(2000, 2010) if IC[y] > OIL[y]]
y10s = [y for y in range(2010, 2020) if IC[y] > OIL[y]]
print(f"[網頁] 2000 年代 {len(y00s)}/10 年、2010 年代 {len(y10s)}/10 年晶片較高（書中：『多數年份』）")
print(f"[網頁] 2017：晶片 {IC[2017]:.1f}，書中寫 2,600 億美元 → 吻合")
print(f"[網頁] 累計 2000–2025 晶片進口 {sum(IC.values()):.0f}、原油 {sum(OIL.values()):.0f}（十億美元）")
print(f"[網頁] 晶片進口高峰 {max(IC, key=IC.get)}：{max(IC.values()):.1f}；2023 低點 {IC[2023]:.1f}")

# ---------- Q1 2025 晶片進口 ÷ 原油進口
r25 = IC[2025] / OIL[2025]
print(f"Q1 2025：{IC[2025]:.1f} ÷ {OIL[2025]:.1f} = {r25:.2f} 倍；差額 {IC[2025]-OIL[2025]:.1f} 十億美元")

# ---------- Q2 2005→2025 晶片進口年複合成長率
cagr = (IC[2025] / IC[2005]) ** (1 / 20) - 1
print(f"Q2 2005→2025 年複合成長率 = ({IC[2025]:.1f}/{IC[2005]:.1f})^(1/20)-1 = {cagr*100:.2f}%（約 {IC[2025]/IC[2005]:.1f} 倍）")

# ---------- Q3 Arm 中國：若依營收占比估值，51% 股權值多少
arm_total = 31.0          # 十億美元（軟銀新聞稿：約 240 億英鎊 ≈ 310 億美元）
share_rev = 1 / 5
stake = 0.51
implied = arm_total * share_rev * stake
print(f"Q3 依營收比例估：{arm_total}×{share_rev}×{stake} = {implied:.3f} 十億美元 = {implied*10:.1f} 億美元；實際 7.75 億 → 只有估值的 {0.775/implied*100:.1f}%")
print(f"   書中寫 400 億美元，若照書中數字：{40*share_rev*stake*10:.1f} 億美元")

# ---------- Q4 大基金三期合計（億人民幣）
fund = {"一期(2014)": 1387, "二期(2019)": 2040, "三期(2024)": 3440}
print(f"Q4 大基金三期合計 = {sum(fund.values())} 億人民幣；三期是一期的 {fund['三期(2024)']/fund['一期(2014)']:.2f} 倍")

# ---------- 網頁：晶片出口（HS 8542，flowCode=X）與淨進口
EX = {2000: 2.938, 2001: 2.626, 2002: 4.316, 2003: 6.588, 2004: 11.224, 2005: 14.601,
      2006: 21.555, 2007: 23.874, 2008: 24.693, 2009: 23.614, 2010: 29.608, 2011: 32.900,
      2012: 53.745, 2013: 87.881, 2014: 61.213, 2015: 69.362, 2016: 61.157, 2017: 67.202,
      2018: 85.038, 2019: 102.103, 2020: 116.989, 2021: 154.221, 2022: 154.524, 2023: 136.335,
      2024: 159.747, 2025: 202.696}
net_over = [y for y in IC if IC[y] - EX[y] > OIL[y]]
print(f"[網頁] 淨進口（進口−出口）仍高於原油的年份：{len(net_over)} 年 {net_over}")
print(f"[網頁] 2025 淨進口 {IC[2025]-EX[2025]:.1f} vs 原油 {OIL[2025]:.1f}；出口占進口 {EX[2025]/IC[2025]*100:.0f}%")
