"""EP03 練習題答案與 sims/moore.html 用到的數字：摩爾定律擬合、價格下跌。
用法：python3 calc_u03.py

  摩爾定律（指數成長）  N(t) = N0 * 2^((t - t0) / T2)
  翻倍週期              T2 = (t1 - t0) / log2(N1 / N0)
資料：facts_ep01.yaml 的 14 顆代表晶片（Intel 4004 用 2,300，CHM）；2022 年後 GPU 為多晶粒封裝合計。
書中數字：快捷晶片 120→15 美元（1961-12→1962-10）、20→2 美元（1960 年代中期）；
摩爾 1965 年預測 1975 年 65,000 個元件（CHM 確認：每年翻倍）；Intel 1103 DRAM 1970 年約 1 美分／位元（CHM）。"""
import math

chips = [  # (年份, 電晶體數, 名稱)
    (1971, 2_300, "Intel 4004"), (1978, 29_000, "Intel 8086"), (1985, 275_000, "Intel 80386"),
    (1989, 1_180_235, "Intel 80486"), (1993, 3_100_000, "Pentium"), (2000, 42_000_000, "Pentium 4"),
    (2006, 291_000_000, "Core 2 Duo"), (2013, 1e9, "Apple A7"), (2017, 4.3e9, "Apple A11"),
    (2020, 16e9, "Apple M1"), (2022, 80e9, "NVIDIA H100"), (2023, 92e9, "Apple M3 Max"),
    (2024, 208e9, "NVIDIA Blackwell"), (2026, 336e9, "NVIDIA Rubin"),
]

# ---------- 最小平方法擬合 log2(N) = a + b*t
xs = [c[0] for c in chips]; ys = [math.log2(c[1]) for c in chips]
n = len(xs); mx = sum(xs) / n; my = sum(ys) / n
b = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sum((x - mx) ** 2 for x in xs)
a = my - b * mx
T2 = 1 / b
N1971 = 2 ** (a + b * 1971)
print(f"[擬合] 14 顆晶片：翻倍週期 T2 = {T2:.3f} 年；擬合線在 1971 年 = {N1971:,.0f} 顆")
res = [y - (a + b * x) for x, y in zip(xs, ys)]
print(f"[擬合] 殘差（以倍數計）最大 {2**max(map(abs, res)):.2f} 倍")

# ---------- Q1 摩爾 1965：1965 年約 64 (=2^6) 個元件，每年翻倍到 1975
q1 = 64 * 2 ** (1975 - 1965)
print(f"Q1 64 x 2^10 = {q1:,}（摩爾預測約 65,000）")

# ---------- Q2 以 4004（1971，2,300 顆）為起點、T2 = 2.09 年，推到 2023 年
q2 = 2300 * 2 ** ((2023 - 1971) / 2.09)
print(f"Q2 2,300 x 2^(52/2.09) = {q2:,.0f} 顆 ≈ {q2/1e8:.0f} 億顆")
print(f"   對照 2023 年實際：A17 Pro 190 億、M3 Max 920 億")

# ---------- Q3 4004（1971）→ Rubin（2026）兩點估翻倍週期
q3 = (2026 - 1971) / math.log2(336e9 / 2300)
print(f"Q3 翻倍週期 = 55 / log2(336e9/2300) = 55 / {math.log2(336e9/2300):.2f} = {q3:.2f} 年")

# ---------- Q4 價格跌幅
print(f"Q4 快捷晶片 120 → 15 美元跌 {1 - 15/120:.1%}；20 → 2 美元跌 {1 - 2/20:.1%}；兩段相乘若連續 = 剩 {(15/120)*(2/20):.2%}")

# ---------- Q5 Intel 1103：1,024 位元 x 1 美分
print(f"Q5 1103 一顆約 1024 x 0.01 = {1024*0.01:.2f} 美元")

# ---------- moore.html 用：若晶片售價不變，每顆電晶體相對價格每 T2 年減半
for years in (10, 20, 50):
    print(f"[頁面] 售價不變、T2=2.09：{years} 年後每顆電晶體相對價格 = {2**(-years/2.09):.2e}")
